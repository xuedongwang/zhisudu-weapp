// utils/version.js
// 版本号单一数据源。
//
// 为什么单独抽出来：原先「当前版本」硬编码在 `pages/about/about.wxml` 与
// `pages/mine/mine.wxml` 两处，升到 v1.1.x 后两处都还写着 v1.0.0——
// 属于典型的「文档已升版、界面没跟上」。
// 此后升版只需改这里一处。
//
// ⚠️ 版本显示口径（用户 2026-09-23 确定；2026-09-29 改定对外版本号）：
// 本项目有**两套版本号**，不要混：
//   - 对外发布版本：提审发布的版本号，也是界面上「当前版本」显示的值
//     （1.0.0 首发 → **1.1.0** 功能迭代五批 + 全项目响应式）。
//   - 开发期内部版本 = `v1.0.1` ~ `v1.2.2`、`v1.1`~`v1.5`（批次），以及响应式
//     那批的内部代号 `v2.0`：只存在于 PRD 变更记录、git 提交历史与代码注释，
//     **不进用户界面**——「关于」页的「版本更新历史」只记录**正式发布**的版本。
//
// 首发记录已于 2026-09-23 写入 `pages/about/about.js` 的 VERSIONS。
// **后续每次正式发布**：改这里的 CURRENT_VERSION，并在 VERSIONS 数组最前面追加一条发布记录。
//
// 版本沿革：
//   - 2026-09-24：功能迭代五批（基础纸型 / 形式层 / 机制升级与大尺寸 / 批量导出）合并
//     一次发布，当时拍板对外版本号为 2.0.0。
//   - **2026-09-29：用户改定对外版本号为 `v1.1.0`**——上述五批 + 全项目响应式合并为
//     一次发布，对外按「首发后的第一次功能迭代」呈现。
//     ⚠️ 代码注释与 git 提交信息里的 `v2.0` 是**响应式那批的内部代号**，与对外
//     版本号不是一回事，不要混。


// utils/version.js
// 版本号单一数据源。
//
// 为什么单独抽出来：原先「当前版本」硬编码在 `pages/about/about.wxml` 与
// `pages/mine/mine.wxml` 两处，升到 v1.1.x 后两处都还写着 v1.0.0——
// 属于典型的「文档已升版、界面没跟上」。
// 此后升版只需改这里一处。
//
// ⚠️ 版本显示口径（用户 2026-09-23 确定；同日完成首发记录）：
// 本项目有**两套版本号**，不要混：
//   - 对外发布版本 = `v1.0.0`：本次首次提审发布的版本号，也是界面上「当前版本」显示的值。
//   - 开发期内部版本 = `v1.0.1` ~ `v1.2.2`：只存在于 PRD 变更记录与 git 提交历史，
//     **不进用户界面**——「关于」页的「版本更新历史」只记录**正式发布**的版本。
//
// 因此发布前界面统一显示 v1.0.0、不随内部迭代升版；首发记录已于 2026-09-23
// 写入 `pages/about/about.js` 的 VERSIONS。
// **后续每次正式发布**：改这里的 CURRENT_VERSION，并在 VERSIONS 数组最前面追加一条发布记录。

const CURRENT_VERSION = 'v1.0.0'

module.exports = { CURRENT_VERSION }
